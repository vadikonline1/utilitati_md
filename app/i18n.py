def get_lang(cookie: str | None) -> str:
    """Return a supported language code from a cookie value (default 'ro')."""
    if cookie in LANGS:
        return cookie
    return DEFAULT_LANG


def make_translator(lang: str) -> Callable[[str], str]:
    """Return a translation function for the given language."""
    table = TRANSLATIONS.get(lang, TRANSLATIONS[DEFAULT_LANG])
    return lambda key: table.get(key, key)
